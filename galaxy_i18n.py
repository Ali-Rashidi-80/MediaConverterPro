class I18n:
    def __init__(self, lang='fa'):
        self.lang = lang if lang in STRINGS else 'fa'

    def t(self, key, **kwargs):
        bucket = STRINGS.get(self.lang, STRINGS['en'])
        text = bucket.get(key, STRINGS['en'].get(key, key))
        if kwargs:
            try:
                return text.format(**kwargs)
            except (KeyError, ValueError):
                return text
        return text

    def set_lang(self, lang):
        self.lang = lang if lang in STRINGS else 'fa'

    def is_rtl(self):
        return self.lang == 'fa'


COMBO_LABEL_KEYS = {
    'ui': {'professional': 'pro'},
}


def fill_combo_keys(combo, keys, i18n, prefix, default_key=None, label_keys=None):
    """Fill combo with translated labels and stable userData keys."""
    aliases = dict(COMBO_LABEL_KEYS.get(prefix, {}))
    if label_keys:
        aliases.update(label_keys)
    current = combo.currentData() if combo.count() else default_key
    combo.blockSignals(True)
    combo.clear()
    for key in keys:
        label_key = aliases.get(key, key)
        combo.addItem(i18n.t(f'{prefix}.{label_key}'), key)
    if default_key and current is None:
        current = default_key
    if current is not None:
        idx = combo.findData(current)
        if idx >= 0:
            combo.setCurrentIndex(idx)
    combo.blockSignals(False)


def fill_combo_texts(combo, items, current_text=None):
    """Fill combo with plain text items; preserve selection when possible."""
    if current_text is None and combo.count():
        current_text = combo.currentText()
    combo.blockSignals(True)
    combo.clear()
    combo.addItems(items)
    if current_text:
        idx = combo.findText(current_text)
        if idx >= 0:
            combo.setCurrentIndex(idx)
    combo.blockSignals(False)


def system_font_family(lang='fa'):
    """Cross-platform UI font stack."""
    base = []
    if platform.system() == 'Darwin':
        base = ['-apple-system', 'SF Pro Text', 'Helvetica Neue', 'Arial']
    elif platform.system() == 'Linux':
        base = ['Ubuntu', 'Cantarell', 'Noto Sans', 'DejaVu Sans', 'Arial']
    else:
        base = ['Segoe UI', 'Tahoma', 'Arial']
    if lang == 'fa':
        base = ['Vazirmatn', 'Tahoma'] + base
    return ', '.join(f"'{f}'" for f in base)
